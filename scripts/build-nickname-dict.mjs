import { writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { resolve, dirname } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(__dirname, '../src/lib/nicknameWords.ts')

// ko-nickname의 형용사 목록은 일반 형용사 사전이라 "나쁜"/"못생긴"/"무서운" 같은
// 부정적인 단어도 섞여 있다. korcen/KNU 부정어 리스트는 욕설·강한 부정 감성어만
// 걸러내도록 만들어져 있어 이런 순한 부정 형용사는 못 거른다. 그래서 "긍정의 언어"
// 취지에 맞는 단어만 직접 골라 허용목록으로 사용한다(단어 자체는 여전히 GitHub 원본에서 옴).
const POSITIVE_ADJECTIVE_ALLOWLIST = new Set([
  '고마운', '고운', '곧은', '괜찮은', '귀여운', '기쁜', '깨끗한', '나은', '날랜',
  '낭만적인', '너그러운', '멋진', '반가운', '밝은', '보드라운', '보람찬', '부드러운',
  '뛰어난', '새로운', '아름다운', '알맞은', '예쁜', '올바른', '옳은', '재미있는',
  '점잖은', '좋은', '줄기찬', '즐거운', '지혜로운', '탐스러운', '하나같은', '한결같은',
  '희망찬', '힘찬', '잘생긴', '잘빠진',
])

function parseJsArray(src) {
  const match = src.match(/\[([\s\S]*)\]/)
  if (!match) throw new Error('array not found')
  return JSON.parse(`[${match[1].replace(/,\s*\]/g, ']').replace(/,\s*$/, '')}]`)
}

console.log('ko-nickname 데이터 다운로드 중...')
const [adjRes, animalRes] = await Promise.all([
  fetch('https://raw.githubusercontent.com/warmwhiten/ko-nickname/main/src/adjective.js'),
  fetch('https://raw.githubusercontent.com/warmwhiten/ko-nickname/main/src/animal.js'),
])
if (!adjRes.ok) throw new Error(`adjective HTTP ${adjRes.status}`)
if (!animalRes.ok) throw new Error(`animal HTTP ${animalRes.status}`)

const rawAdjectives = parseJsArray(await adjRes.text())
const animals = parseJsArray(await animalRes.text())

const adjectives = rawAdjectives.filter((w) => POSITIVE_ADJECTIVE_ALLOWLIST.has(w))

const content = `// Auto-generated by scripts/build-nickname-dict.mjs
// Source: ko-nickname (https://github.com/warmwhiten/ko-nickname), MIT License
// Adjectives narrowed to a hand-picked positive-language allowlist (see POSITIVE_ADJECTIVE_ALLOWLIST
// in the build script) since the source list is a general adjective dictionary, not a positive one.
// Adjectives: ${adjectives.length} (of ${rawAdjectives.length} source entries), Animals: ${animals.length}
export const NICKNAME_ADJECTIVES: string[] = ${JSON.stringify(adjectives, null, 2)}

export const NICKNAME_ANIMALS: string[] = ${JSON.stringify(animals, null, 2)}

export function generateFallbackNickname(): string {
  const adjective = NICKNAME_ADJECTIVES[Math.floor(Math.random() * NICKNAME_ADJECTIVES.length)]
  const animal = NICKNAME_ANIMALS[Math.floor(Math.random() * NICKNAME_ANIMALS.length)]
  return \`\${adjective} \${animal}\`
}
`

writeFileSync(OUT, content, 'utf8')
console.log(`완료: 형용사 ${adjectives.length}개(원본 ${rawAdjectives.length}개 중 필터링), 동물 ${animals.length}개 → ${OUT}`)
